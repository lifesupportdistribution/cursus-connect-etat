export const remplir = (modele, v = {}) => String(modele).replace(/\{(\w+)\}/g, (m, k) => (v[k] != null ? String(v[k]) : m));

/* La langue à afficher. `stockage` et `navigateur` sont passés pour rester testables. */
export function langueChoisie({ recherche = "", stockage = null, navigateur = [] } = {}) {
  let demandee = null;
  try { demandee = new URLSearchParams(recherche).get("lang"); } catch { demandee = null; }
  if (LANGUES.includes(demandee)) return demandee;
  if (LANGUES.includes(stockage)) return stockage;
  for (const l of navigateur || []) { const c = String(l || "").slice(0, 2).toLowerCase(); if (LANGUES.includes(c)) return c; }
  return "fr";
}

export const traduireCause = (cause, langue) => (langue === "fr" ? cause : (CAUSES[cause] && CAUSES[cause][langue]) || cause);
